package com.vishatech.erp.security;

import jakarta.annotation.PostConstruct;
import java.sql.Connection;
import java.sql.Statement;
import javax.sql.DataSource;
import org.junit.jupiter.api.BeforeEach;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;

/**
 * Shared base for the security test suite.
 *
 * Injects the H2 JDBC URL from Java code (no properties-file escaping issues).
 * The INIT parameter defines the TEXT / LONGTEXT domains the entities use via
 * {@code @Column(columnDefinition = "TEXT"/"LONGTEXT")} before Hibernate DDL
 * runs — H2 has no native TEXT/LONGTEXT types.
 *
 * The shared {@code audit_logs} table uses a MySQL JSON column definition that
 * is emitted as a quoted type by Hibernate's globally quoted H2 configuration.
 * H2 treats that quoted type as a missing domain, so the test schema creates
 * the two JSON payload columns as CLOBs. Audit payloads are already serialized
 * strings at this boundary, while production continues to use MySQL JSON.
 */
public abstract class AbstractSecurityTest {

    @Autowired
    private DataSource dataSource;

    /**
     * {@code RateLimiter} is a per-context bean whose windows are keyed by
     * client IP. Several test classes share one cached context (identical
     * {@code @TestPropertySource}), and every MockMvc call reaches it from the
     * same IP, so those classes also share ONE auth budget: a class could then
     * receive 429 for {@code POST /auth/login|register|refresh} merely because
     * of what ran before it, instead of its own assertion.
     *
     * <p>Clearing the auth windows here makes each test method start from its
     * own budget, so the classes are order-independent and a re-run behaves
     * like a first run. It does not weaken the limiter: the throttling itself is
     * still exercised and asserted inside a single method with a deliberately
     * small budget by {@code RateLimitTests}, and the production limits are
     * unchanged ({@code AuthRateLimitIsolationTests} pins both).
     */
    @Autowired(required = false)
    private RateLimiter rateLimiter;

    @BeforeEach
    void isolateAuthRateLimitWindows() {
        if (rateLimiter == null) {
            return;
        }
        // the per-IP buckets of AuthRateLimitFilter
        rateLimiter.clear("auth:");
        // the per-email+IP bucket of AuthService
        rateLimiter.clear("login:");
    }

    @DynamicPropertySource
    static void h2DataSource(DynamicPropertyRegistry registry) {
        registry.add("spring.datasource.url", () ->
                "jdbc:h2:mem:erptest;MODE=MySQL;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE"
                        + ";INIT=CREATE DOMAIN IF NOT EXISTS \"TEXT\" AS CLOB"
                        + "\\;CREATE DOMAIN IF NOT EXISTS \"LONGTEXT\" AS CLOB"
                        + "\\;CREATE DOMAIN IF NOT EXISTS \"MEDIUMBLOB\" AS BLOB");
    }

    /**
     * Recreates the audit_logs table after Hibernate's create-drop phase
     * (which cannot create the quoted JSON columns in H2). The indexes are
     * created here as well so the test schema matches the entity declaration.
     */
    @PostConstruct
    void ensureAuditLogsTable() throws Exception {
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement()) {
            statement.execute("CREATE TABLE IF NOT EXISTS audit_logs ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "created_at TIMESTAMP WITH TIME ZONE NOT NULL, "
                    + "updated_at TIMESTAMP WITH TIME ZONE, "
                    + "entity_id VARCHAR(100), "
                    + "entity_type VARCHAR(100) NOT NULL, "
                    + "ip_address VARCHAR(100), "
                    + "request_id VARCHAR(100), "
                    + "description CLOB, "
                    + "entity_display_id VARCHAR(255), "
                    + "new_value CLOB, "
                    + "old_value CLOB, "
                    + "user_id VARCHAR(255), "
                    + "username VARCHAR(255), "
                    + "action VARCHAR(40) NOT NULL, "
                    + "module VARCHAR(40) NOT NULL)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_audit_user_id "
                    + "ON audit_logs (user_id)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_audit_module "
                    + "ON audit_logs (module)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_audit_entity_type "
                    + "ON audit_logs (entity_type)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_audit_entity_id "
                    + "ON audit_logs (entity_id)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_audit_action "
                    + "ON audit_logs (action)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_audit_created_at "
                    + "ON audit_logs (created_at)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_audit_module_entity "
                    + "ON audit_logs (module, entity_type, entity_id)");
            statement.execute("CREATE INDEX IF NOT EXISTS idx_audit_user_module "
                    + "ON audit_logs (user_id, module)");
        }
    }
}
