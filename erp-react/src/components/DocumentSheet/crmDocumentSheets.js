/* Every lookup here is an AUXILIARY one: it only decides whether the canvas can
 * render the document natively. A document whose source record has since been
 * deleted still has a perfectly valid file, so the failure is handled in place
 * (the caller falls back to the stored file) instead of replacing the page with
 * the global error page. */
const AUXILIARY = { suppressGlobalError: true };

const SHEETS = {
  lead: { spec: LEAD, load: (id) => leadService.getLead(id, AUXILIARY) },
  client: { spec: CLIENT, load: (id) => customerService.get(id, AUXILIARY) },
  followup: { spec: FOLLOWUP, load: (id) => followUpService.get(id, AUXILIARY) }
};

/**
 * The document module → sheet key, canonicalized (lower-case, alphanumerics
 * only) so the legacy/mixed-case module strings already stored on document rows
 * ("Follow-up", "followUp", "Lead") all resolve to the same sheet.
 * Returns null for a module this file has no layout for — the caller then keeps
 * its previous preview behaviour rather than inventing a document.
 */
export function crmSheetKey(module) {
  const key = String(module || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  if (key === 'lead' || key === 'leads') return 'lead';
  if (key === 'client' || key === 'clients' || key === 'customer' || key === 'customers') return 'client';
  if (key === 'followup' || key === 'followups') return 'followup';
  return null;
}

/**
 * Resolve the real record a document was generated from, through the EXISTING
 * module endpoint, and pair it with this module's sheet spec.
 *
 * Resolves to `{ key, spec, record }`, or null when the module has no CRM sheet
 * or the document carries no usable source record — never a partial or guessed
 * document. The caller renders nothing new in that case.
 */
export async function loadCrmSheetRecord(module, relatedRecordId, doc) {
  const key = crmSheetKey(module);
  const entry = key ? SHEETS[key] : null;
  const recordId = Number(relatedRecordId);
  if (!entry || !Number.isFinite(recordId) || recordId <= 0) return null;

  const record = payloadOf(await entry.load(recordId));
  if (!record || typeof record !== 'object' || record.id == null) return null;

  return { key, spec: entry.spec, record, doc: doc || null };
}
