// ============================================================================
// crmDocumentSheets — the document layout of the CRM-owned document types
// (Lead / Client / Follow-up) plus the loader that resolves the real record.
//
// These three types are the only ones stored in the Documents module that have
// NO design workspace of their own, so Documents → View / Preview is their
// primary preview surface. Until now that surface could only show the stored
// PDF frame; these specs let it show the SAME document the backend renders to
// that PDF instead.
//
// Row lists mirror the backend's authoritative layouts — PdfGenerationService
// generateLeadHtml() / generateClientHtml() / generateFollowUpHtml() — labels
// and order included, so the on-screen sheet and the stored file say the same
// thing. Two deliberate differences, both required by the Documents preview:
//
//   • JSON-bearing fields (Lead "Notes", Follow-up "Subject" / "Discussion")
//     pass through the existing notesDisplayText() parser, so the CRM metadata
//     envelope ({"__crmMeta":{…}}) is never rendered as raw JSON. A written
//     remark is kept; a value with no human-readable text is dropped.
//   • Empty rows are omitted instead of printing the '-'. The written document
//     is allowed a wall of dashes; a preview is not.
//
// Nothing is fetched here for the record's own content and no value is
// invented: every row is read from the record the backend resolves for the
// document (GET /leads/{id}, /customers/{id}, /followups/{id}) through the
// existing services.
// ============================================================================
import leadService from '../../services/leadService';
import customerService from '../../services/customerService';
import followUpService from '../../services/followUpService';
import { payloadOf } from '../../utils/documentView';
import { formatINR, formatLeadNo, formatDate } from '../../utils/leadHelpers';
import { notesDisplayText } from '../../utils/leadNotes';

/* ─── value hygiene ───
 * A document cell shows text. Anything that is not plain text — an array
 * (contacts, attachments), an object, or a string that is really JSON — is
 * dropped rather than rendered, so no technical value can leak into the sheet
 * from a field this spec has not been taught about yet. */
const LOOKS_LIKE_JSON = /^[[{]/;
const EMPTY_JSON = new Set(['[]', '{}', '[{}]', '[[]]']);

function clean(value) {
  if (value == null) return '';
  if (Array.isArray(value) || typeof value === 'object') return '';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : '';
  if (typeof value !== 'string') return '';
  const text = value.trim();
  if (!text || EMPTY_JSON.has(text) || LOOKS_LIKE_JSON.test(text)) return '';
  return text;
}

/** A date cell, formatted like the rest of the ERP; '' when there is no date. */
const dateCell = (value) => (value ? formatDate(value) : '');

/** A money cell in the record's currency; '' when there is nothing to show. */
const moneyCell = (value, currency = 'INR') => {
  const num = Number(value);
  return Number.isFinite(num) && num !== 0 ? formatINR(num, currency) : '';
};

/** A notes cell: only the human-readable text, never the CRM metadata envelope. */
const notesCell = (value) => clean(notesDisplayText(value));

/** Drops empty [label, value] rows and normalizes everything to text. */
const rows = (...pairs) => pairs
  .map(([label, value]) => [label, clean(value)])
  .filter(([, value]) => value);

