const DATE_LIKE = /^\d{4}-\d{2}-\d{2}T/;

// Normalise a backend record into editable form state: dates become plain
// yyyy-mm-dd so <input type="date"> round-trips cleanly.
function docToForm(raw) {
  const out = {};
  Object.keys(raw || {}).forEach((key) => {
    if (key === 'items' || key === 'history' || key === 'timeline' || key === 'revisions') return;
    const v = raw[key];
    if (typeof v === 'string' && DATE_LIKE.test(v)) out[key] = v.slice(0, 10);
    else out[key] = v;
  });
  return out;
}

// ===== Content-tab field rendering =====
// The Content tab reuses each module's own form schema (SALES_FORM_CONFIGS
// sections) so the preview editor always matches the create/edit forms.

const SKIP_FIELD_TYPES = new Set(['hidden', 'display', 'listEditor']);
const SKIP_FIELD_KEYS = new Set(['clientId', 'status']);

function optionValue(o) {
  if (o && typeof o === 'object') return String(o.value ?? o.label ?? '');
  return String(o ?? '');
}

function optionLabel(o) {
  if (o && typeof o === 'object') return String(o.label ?? o.value ?? '');
  return String(o ?? '');
}

function contentSections(formConfig) {
  const sections = [];
  (formConfig?.sections || []).forEach((section) => {
    const fields = (section.fields || [])
      .filter((f) => !SKIP_FIELD_TYPES.has(f.type) && !SKIP_FIELD_KEYS.has(f.key))
      .map((f) => ({ ...f }));
    // Nested groups (exporter/buyer/consignee etc.) flatten into the section.
    (section.groups || []).forEach((group) => {
      (group.fields || [])
        .filter((f) => !SKIP_FIELD_TYPES.has(f.type) && !SKIP_FIELD_KEYS.has(f.key))
        .forEach((f) => fields.push({ ...f, groupTitle: group.title }));
    });
    if (fields.length > 0) sections.push({ title: section.title, fields });
  });
  return sections;
}

