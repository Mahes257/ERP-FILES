  const toggleItem = (idx) => {
    setExpandedItems((prev) => {
      const next = new Set(prev);
      if (next.has(idx)) next.delete(idx);
      else next.add(idx);
      return next;
    });
  };

  const expandItem = (idx) => {
    setExpandedItems((prev) => new Set(prev).add(idx));
  };

  const defaultItem = (extra = {}) => ({
    description: '',
    qty: 1,
    rate: 0,
    gstRate: 18,
    sku: '',
    unit: '',
    hsn: '',
    drawingNo: '',
    material: '',
    leadTime: '',
    descriptionRows: [],
    ...extra
  });

