  const totalQty = items.reduce((sum, it) => sum + (Number(it.qty) || 0), 0);
  // ===== Item grid ==========================================================
  // The A4 sheet renders the SAME item grid as the Sales Document workspace and
  // the /quotations/new form (quotation-create.css it-* classes):
  //   S.NO | SKU | QTY | UOM | HSN | ITEM DESCRIPTION | GST | RATE | AMOUNT
