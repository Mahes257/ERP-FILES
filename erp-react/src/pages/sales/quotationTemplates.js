const KEY_TO_TEMPLATE = new Map(QUOTATION_TEMPLATES.map((t) => [t.key, t]));

export function quotationTemplateFor(key) {
  return KEY_TO_TEMPLATE.get(key) || null;
}

export function quotationTemplateKey(key) {
  if (!key) return DEFAULT_TEMPLATE_KEY;
  if (KEY_TO_TEMPLATE.has(key)) return key;
  return LEGACY_TEMPLATE_MAP[key] || DEFAULT_TEMPLATE_KEY;
}

export function autoGenerateDesign(seed) {
  const s = String(seed == null ? '' : seed);
  let h = 0;
  for (let i = 0; i < s.length; i += 1) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return { template: QUOTATION_TEMPLATES[h % QUOTATION_TEMPLATES.length].key };
}